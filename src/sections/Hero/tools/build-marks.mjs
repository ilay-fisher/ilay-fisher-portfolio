/* global process, console */
// Dev-time generator (not shipped): copies the 24x24 SVG path data of the technology marks printed on the
// hero keys out of simple-icons (a devDependency) into a self-hosted data file, so the app makes no
// runtime third-party request and does not ship the whole icon set. Run from the repo root:
//   node src/sections/Hero/tools/build-marks.mjs > src/sections/Hero/scene/marks.ts
import * as si from 'simple-icons';
import fs from 'node:fs';
import { vendorMarks } from './vendor.mjs';

const pkg = JSON.parse(fs.readFileSync('node_modules/simple-icons/package.json', 'utf8'));

const SLUGS = [
  'android',
  'kotlin',
  'tensorflow',
  'react',
  'firebase',
  'git',
  'python',
  'jetpackcompose',
  'typescript',
  'nodedotjs',
  'pytorch',
  'onnx',
  'cplusplus',
  'webassembly',
  'docker',
  'postgresql',
  'fastapi',
  'opencv',
  'github',
  'googlecloud',
  'claude',
];

const cap = (s) => 'si' + s[0].toUpperCase() + s.slice(1);
const out = [];
out.push(
  '// GENERATED by tools/build-marks.mjs from simple-icons ' +
    pkg.version +
    '. Do not edit by hand.',
);
out.push(
  '// Path data (24x24 viewBox) is CC0-1.0 (simple-icons). The marks themselves are trademarks of their',
);
out.push(
  '// respective owners, printed flat and unaltered to indicate the technologies the owner works with.',
);
out.push('');
out.push('/** One self-hosted brand mark. */');
out.push('export interface Mark {');
out.push('  title: string;');
out.push('  /** SVG path data in a 24x24 box. */');
out.push('  path: string;');
out.push('  /** Official brand colour, upper-case hex without `#`. */');
out.push('  hex: string;');
out.push(
  '  /** Where the mark was taken from (the brand owner resource listed by simple-icons). */',
);
out.push('  source: string;');
out.push('  /** Brand guidelines page, when one exists. */');
out.push('  guidelines: string | null;');
out.push(
  '  /** Licence of the mark artwork as stated by simple-icons, or the data licence when none is stated. */',
);
out.push('  licence: string;');
out.push('}');
out.push('');
out.push('export const MARKS: Record<string, Mark> = {');
for (const slug of SLUGS) {
  const i = si[cap(slug)];
  if (!i) {
    console.error('missing mark: ' + slug);
    process.exit(1);
  }
  const licence = i.license
    ? i.license.type + ' (' + i.license.url + ')'
    : 'CC0-1.0 (simple-icons data); trademark of its owner';
  out.push('  ' + JSON.stringify(slug) + ': {');
  out.push('    title: ' + JSON.stringify(i.title) + ',');
  out.push('    path: ' + JSON.stringify(i.path) + ',');
  out.push('    hex: ' + JSON.stringify(i.hex) + ',');
  out.push('    source: ' + JSON.stringify(i.source) + ',');
  out.push('    guidelines: ' + JSON.stringify(i.guidelines ?? null) + ',');
  out.push('    licence: ' + JSON.stringify(licence) + ',');
  out.push('  },');
}
for (const [slug, i] of Object.entries(vendorMarks())) {
  out.push('  ' + JSON.stringify(slug) + ': {');
  out.push('    title: ' + JSON.stringify(i.title) + ',');
  out.push('    path: ' + JSON.stringify(i.path) + ',');
  out.push('    hex: ' + JSON.stringify(i.hex) + ',');
  out.push('    source: ' + JSON.stringify(i.source) + ',');
  out.push('    guidelines: ' + JSON.stringify(i.guidelines) + ',');
  out.push('    licence: ' + JSON.stringify(i.licence) + ',');
  out.push('  },');
}
out.push('};');
out.push('');
process.stdout.write(out.join('\n'));
