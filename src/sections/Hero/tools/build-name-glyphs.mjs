/* eslint-disable no-undef -- Node-only dev script */
// Dev-time generator (not shipped): turns Bricolage Grotesque ExtraBold into the glyph outlines
// used for the 3D name. Run: node build-name-glyphs.mjs <font.woff> > ../scene/nameGlyphs.ts
// opentype.js is used from a scratch install; the output is committed, so the app has no font parser.
import fs from 'node:fs';
import opentype from 'opentype.js';

const buf = fs.readFileSync(process.argv[2]);
const font = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));
const SIZE = 1000;
const r = (n) => Math.round(n * 1000) / 1000;

function flatten(cmds) {
  const pts = [];
  let cx = 0, cy = 0;
  for (const c of cmds) {
    if (c.type === 'M' || c.type === 'L') { cx = c.x; cy = c.y; pts.push([cx, cy]); }
    else if (c.type === 'Q') {
      for (let i = 1; i <= 8; i++) { const t = i / 8, u = 1 - t;
        pts.push([u*u*cx + 2*u*t*c.x1 + t*t*c.x, u*u*cy + 2*u*t*c.y1 + t*t*c.y]); }
      cx = c.x; cy = c.y;
    } else if (c.type === 'C') {
      for (let i = 1; i <= 8; i++) { const t = i / 8, u = 1 - t;
        pts.push([u**3*cx + 3*u*u*t*c.x1 + 3*u*t*t*c.x2 + t**3*c.x, u**3*cy + 3*u*u*t*c.y1 + 3*u*t*t*c.y2 + t**3*c.y]); }
      cx = c.x; cy = c.y;
    }
  }
  return pts;
}
const box = (pts) => pts.length ? [r(Math.min(...pts.map(p=>p[0]))), r(Math.min(...pts.map(p=>p[1]))), r(Math.max(...pts.map(p=>p[0]))), r(Math.max(...pts.map(p=>p[1])))] : null;

function word(text) {
  const glyphs = [];
  // charToGlyph + manual kerning: opentype's shaping path chokes on this font's GSUB tables.
  let x = 0;
  const chars = [...text];
  chars.forEach((chr, i) => {
    const glyph = font.charToGlyph(chr);
    const fs = SIZE;
    const p = glyph.getPath(x, 0, fs);
    const next = chars[i + 1];
    x += (glyph.advanceWidth / font.unitsPerEm) * SIZE + (next ? (font.getKerningValue(glyph, font.charToGlyph(next)) / font.unitsPerEm) * SIZE : 0);
    // y-down to y-up, em units
    const cmds = p.commands.map((c) => ({ ...c, y: -c.y, y1: -c.y1, y2: -c.y2 }));
    const norm = cmds.map((c) => {
      const o = { type: c.type };
      for (const k of ['x', 'y', 'x1', 'y1', 'x2', 'y2']) if (c[k] !== undefined && !Number.isNaN(c[k])) o[k] = c[k] / SIZE;
      return o;
    });
    const d = norm.map((c) => c.type === 'Z' ? 'Z' : c.type + ({M:[c.x,c.y],L:[c.x,c.y],Q:[c.x1,c.y1,c.x,c.y],C:[c.x1,c.y1,c.x2,c.y2,c.x,c.y]}[c.type]).map(r).join(' ')).join('');
    const pts = flatten(norm);
    const body = box(pts.filter((q) => q[1] >= 0));
    const tail = box(pts.filter((q) => q[1] < 0));
    glyphs.push({ ch: chr, d, bbox: box(pts), body, tail });
  });
  return glyphs;
}
const out = { capHeight: r(font.tables.os2.sCapHeight / font.unitsPerEm), xHeight: r(font.tables.os2.sxHeight / font.unitsPerEm), words: { Ilay: word('Ilay'), Fisher: word('Fisher') } };
console.log(`/* GENERATED by tools/build-name-glyphs.mjs from Bricolage Grotesque ExtraBold (SIL OFL). Em units, y up, baseline 0. */
export interface GlyphData { ch: string; d: string; bbox: [number, number, number, number]; body: [number, number, number, number] | null; tail: [number, number, number, number] | null }
export const NAME_GLYPHS: { capHeight: number; xHeight: number; words: { Ilay: GlyphData[]; Fisher: GlyphData[] } } = ${JSON.stringify(out)} as never;`);
